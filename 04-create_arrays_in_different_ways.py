import numpy as np

print("Create an array containing numbers from 0 to 9")
arr =np.arange(0,10)
print(arr)

print("Create an array containing five zeros.")
zeros_arr=np.zeros(5)
print(zeros_arr)

print("Create an array containing four ones.")
ones_arr=np.ones(4)
print(ones_arr)

print("Create an array containing even numbers from 2 to 20.")
even_arr=np.arange(2,21,2)
print(even_arr)

print("Create an array of 10 random integers between 1 and 100, inclusive.")
random_arr=np.random.randint(1,101,10)
print(random_arr)


